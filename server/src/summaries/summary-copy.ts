export function moodOpening(mood: string, periodLabel: string): string {
  const prefix = periodLabel.includes('月') ? '这个月' : '这一年';
  const suffixes: Record<string, string> = {
    开心: '那些明亮的时刻，被你好好留了下来。',
    平静: '在许多普通日子里，你找到了自己的节奏。',
    难过: '有些日子并不轻松，但你仍然认真走过。',
    焦虑: '焦虑出现得比较频繁，但你仍然一步一步走到了这里。',
    感动: '你被一些瞬间打动，也把它们认真保存了下来。',
    疲惫: '你经历了不少疲惫，也没有忘记记录真实的自己。',
  };
  return `${prefix}，${mood}是你记录最多的情绪。${suffixes[mood] ?? '这份感受，成为了这一段生活的一部分。'}`;
}
